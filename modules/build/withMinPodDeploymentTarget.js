// withMinPodDeploymentTarget.js
//
// Expo Config Plugin: raises every CocoaPods target whose iOS deployment
// target is below 16.0 up to 16.0. The app target itself is set to 16.0
// through expo-build-properties in app.json.
//
// Xcode 27 refuses to build targets below iOS 15.0 (older Xcode only warned).
// Several pods in this app still declare 9.0-13.0 (GoogleSignIn, AppAuth,
// SDWebImage, SwiftProtobuf, RNSVG...), so the iOS build fails before it
// compiles. 16.0 rather than 15.1 because expo-router 55 calls an iOS 16 API
// without an availability check (LinkPreviewNativeActionView.swift), which
// Xcode 27 also rejects, and Expo's own module then requires 16.0 for the app.
// Pods that already need a higher minimum are left alone.
//
// Applied as a config plugin because `ios/` is gitignored and regenerated by
// `expo prebuild`, so an edit to the generated Podfile would be lost.

const { withPodfile, createRunOncePlugin } = require('@expo/config-plugins');

const MIN_IOS = '16.0';
const MARKER = '# withMinPodDeploymentTarget';

const SNIPPET = `
    ${MARKER}
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |build_config|
        current = build_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current.nil? || Gem::Version.new(current) < Gem::Version.new('${MIN_IOS}')
          build_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${MIN_IOS}'
        end
      end
    end`;

const withMinPodDeploymentTarget = (config) =>
  withPodfile(config, (modConfig) => {
    const podfile = modConfig.modResults.contents;
    if (podfile.includes(MARKER)) return modConfig;

    modConfig.modResults.contents = podfile.replace(
      /post_install do \|installer\|/,
      (match) => `${match}${SNIPPET}`
    );

    if (modConfig.modResults.contents === podfile) {
      console.warn(
        '[withMinPodDeploymentTarget] no post_install block found in the Podfile; deployment targets left unchanged'
      );
    }
    return modConfig;
  });

module.exports = createRunOncePlugin(
  withMinPodDeploymentTarget,
  'withMinPodDeploymentTarget',
  '1.0.0'
);
